"""Provider boundary. Every method is synchronous and must run in a bounded DB worker."""

from typing import Any, Protocol

from ...config import Config


class UnsupportedMetadataError(ValueError):
    """The provider cannot safely retrieve this metadata for the selected source."""


class Backend(Protocol):
    def connect(self, cfg: Config) -> Any: ...
    def fetch_snapshot(self, cfg: Config, conn: Any = None) -> Any: ...
    def fetch_fingerprints(self, cfg: Config, conn: Any = None) -> Any: ...
    def get_object_definition(
        self, cfg: Config, schema: str, name: str, object_type: str | None = None
    ) -> str | None: ...
    def get_object_dependencies(self, cfg: Config, schema: str, name: str) -> list[tuple]: ...
    def describe_result_schema(self, cursor: Any, sql: str) -> list[dict]: ...
    def convert_value(self, value: Any, cfg: Config) -> Any: ...
    def capabilities(self, cfg: Config) -> dict: ...
