-- Run as DBMCP_TEST on EACH of two disposable Oracle databases, once.
-- DBA creates DBMCP_TEST with CREATE SESSION/TABLE/VIEW/PROCEDURE/SYNONYM,
-- CREATE DATABASE LINK and a bounded tablespace quota. Never run in production.
WHENEVER SQLERROR EXIT SQL.SQLCODE
CREATE TABLE DBMCP_CUSTOMERS (
 TENANT_ID NUMBER(10) NOT NULL, ID NUMBER(10) NOT NULL, NAME VARCHAR2(80 CHAR),
 CONSTRAINT DBMCP_CUSTOMERS_PK PRIMARY KEY (TENANT_ID,ID));
CREATE TABLE DBMCP_ORDERS (
 TENANT_ID NUMBER(10) NOT NULL, ORDER_ID NUMBER(10) NOT NULL, CUSTOMER_ID NUMBER(10),
 AMOUNT NUMBER(19,4), NOTE CLOB, PAYLOAD BLOB, CREATED_AT TIMESTAMP(6) WITH TIME ZONE,
 CONSTRAINT DBMCP_ORDERS_PK PRIMARY KEY(TENANT_ID,ORDER_ID),
 CONSTRAINT DBMCP_ORDERS_CUSTOMER_FK FOREIGN KEY(TENANT_ID,CUSTOMER_ID)
 REFERENCES DBMCP_CUSTOMERS(TENANT_ID,ID));
CREATE INDEX DBMCP_ORDERS_CUSTOMER_IX ON DBMCP_ORDERS(TENANT_ID,CUSTOMER_ID);
COMMENT ON TABLE DBMCP_ORDERS IS '測試訂單';
COMMENT ON COLUMN DBMCP_ORDERS.AMOUNT IS '精確金額';
INSERT INTO DBMCP_CUSTOMERS VALUES(1,1,'測試客戶');
INSERT INTO DBMCP_ORDERS VALUES(1,1,1,123.4500,TO_CLOB(RPAD('N',4000,'N')),HEXTORAW('01020304'),SYSTIMESTAMP);
INSERT INTO DBMCP_ORDERS(TENANT_ID,ORDER_ID,CUSTOMER_ID,AMOUNT) VALUES(1,2,1,2.5);
COMMIT;
CREATE VIEW DBMCP_ORDER_SUMMARY AS SELECT TENANT_ID,SUM(AMOUNT) TOTAL_AMOUNT FROM DBMCP_ORDERS GROUP BY TENANT_ID;
CREATE SYNONYM DBMCP_LOCAL_ORDERS FOR DBMCP_ORDERS;
CREATE SYNONYM DBMCP_CHAIN FOR DBMCP_LOCAL_ORDERS;
CREATE OR REPLACE PACKAGE DBMCP_PKG AS FUNCTION ORDER_COUNT RETURN NUMBER; END;
/
CREATE OR REPLACE PACKAGE BODY DBMCP_PKG AS
 FUNCTION ORDER_COUNT RETURN NUMBER IS N NUMBER;
 BEGIN SELECT COUNT(*) INTO N FROM DBMCP_ORDERS; RETURN N; END;
END;
/
